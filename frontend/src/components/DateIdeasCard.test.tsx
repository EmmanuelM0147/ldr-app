import { render, screen, waitFor } from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import { MemoryRouter } from "react-router-dom"
import { describe, expect, it, vi } from "vitest"
import { ApiError } from "../api/errors"
import { DateIdeasCard } from "./DateIdeasCard"

describe("DateIdeasCard", () => {
  it("shows enable-in-settings when AI is off", () => {
    render(
      <MemoryRouter>
        <DateIdeasCard aiEnabled={false} client={{ createDateIdeas: vi.fn() }} />
      </MemoryRouter>,
    )
    expect(screen.getByText(/AI is off — enable in Settings/i)).toBeInTheDocument()
    expect(screen.getByRole("link", { name: /Open Settings/i })).toHaveAttribute("href", "/settings")
  })

  it("loads ideas and labels them as Generated by AI", async () => {
    const user = userEvent.setup()
    const createDateIdeas = vi.fn().mockResolvedValue({
      ideas: [
        {
          title: "Suya picnic",
          description: "Share suya at the park.",
          est_cost: "₦5,000",
        },
      ],
    })
    render(
      <MemoryRouter>
        <DateIdeasCard aiEnabled client={{ createDateIdeas }} />
      </MemoryRouter>,
    )
    await user.type(screen.getByLabelText(/Budget/i), "5000 NGN")
    await user.click(screen.getByRole("button", { name: /Get ideas/i }))
    await waitFor(() => expect(createDateIdeas).toHaveBeenCalled())
    expect(screen.getByText("Generated by AI")).toBeInTheDocument()
    expect(screen.getByText("Suya picnic")).toBeInTheDocument()
  })

  it("shows an error state when the request fails", async () => {
    const user = userEvent.setup()
    const createDateIdeas = vi.fn().mockRejectedValue(new ApiError(429, "Daily AI idea limit reached."))
    render(
      <MemoryRouter>
        <DateIdeasCard aiEnabled client={{ createDateIdeas }} />
      </MemoryRouter>,
    )
    await user.type(screen.getByLabelText(/Budget/i), "low")
    await user.click(screen.getByRole("button", { name: /Get ideas/i }))
    await waitFor(() => expect(screen.getByText(/Daily AI idea limit reached/i)).toBeInTheDocument())
  })
})
