import { useState, type FormEvent } from "react"
import { Link } from "react-router-dom"
import { ApiError } from "../api/errors"
import type { DateIdea, DateIdeasRequest } from "../types"

type ClientLike = {
  createDateIdeas: (input: DateIdeasRequest) => Promise<{ ideas: DateIdea[] }>
}

export function DateIdeasCard({
  aiEnabled,
  client,
}: {
  aiEnabled: boolean
  client: ClientLike
}) {
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [ideas, setIdeas] = useState<DateIdea[] | null>(null)

  if (!aiEnabled) {
    return (
      <section className="card" aria-labelledby="date-ideas-heading">
        <h2 id="date-ideas-heading">Date night ideas</h2>
        <p className="muted">AI is off — enable in Settings.</p>
        <Link className="secondary button-link" to="/settings">
          Open Settings
        </Link>
      </section>
    )
  }

  async function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    const form = new FormData(event.currentTarget)
    const duration = Number(form.get("duration_minutes"))
    const budget = String(form.get("budget") ?? "").trim()
    const mode = String(form.get("mode") ?? "together")
    const mood = String(form.get("mood") ?? "").trim()
    if (mode !== "together" && mode !== "apart") {
      setError("Choose together or apart.")
      return
    }
    setBusy(true)
    setError(null)
    try {
      const result = await client.createDateIdeas({
        duration_minutes: duration,
        budget,
        mode,
        mood: mood || undefined,
      })
      setIdeas(result.ideas)
    } catch (caught) {
      setError(caught instanceof ApiError ? caught.detail : "Could not get ideas.")
      setIdeas(null)
    } finally {
      setBusy(false)
    }
  }

  return (
    <section className="card" aria-labelledby="date-ideas-heading">
      <h2 id="date-ideas-heading">Date night ideas</h2>
      <p className="muted">
        Sends only duration, budget, mode, and optional mood — never names, notes, or other couple content.
      </p>
      <form className="stack" onSubmit={(event) => void onSubmit(event)}>
        <label className="field">
          <span>Duration (minutes)</span>
          <input name="duration_minutes" type="number" min={15} max={720} defaultValue={120} required />
        </label>
        <label className="field">
          <span>Budget</span>
          <input name="budget" type="text" maxLength={80} placeholder="e.g. 5000 NGN" required />
        </label>
        <label className="field">
          <span>Mode</span>
          <select name="mode" defaultValue="together">
            <option value="together">Together in person</option>
            <option value="apart">Apart (remote)</option>
          </select>
        </label>
        <label className="field">
          <span>Mood (optional)</span>
          <input name="mood" type="text" maxLength={80} placeholder="quiet, playful…" />
        </label>
        <button type="submit" disabled={busy}>
          {busy ? "Generating…" : "Get ideas"}
        </button>
      </form>
      {busy ? <p className="muted">Generating ideas…</p> : null}
      {error ? <p className="error">{error}</p> : null}
      {ideas ? (
        <ul className="list idea-results">
          {ideas.map((idea) => (
            <li key={`${idea.title}-${idea.est_cost}`} className="idea-card">
              <p className="ai-label">Generated by AI</p>
              <strong>{idea.title}</strong>
              <p>{idea.description}</p>
              <p className="muted">Est. cost: {idea.est_cost}</p>
            </li>
          ))}
        </ul>
      ) : null}
    </section>
  )
}
